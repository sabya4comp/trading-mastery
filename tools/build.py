#!/usr/bin/env python3
"""Build data/content.json and js/data.js from the content modules, with validation."""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

import content_steidlmayer as som
import content_mip as mip
import content_mom as mom
import content_momentum_a as mma
import content_momentum_b as mmb

books = []
for mod, extra in ((som, None), (mip, None), (mom, None), (mma, mmb)):
    b = dict(mod.BOOK)
    chs = [dict(c) for c in mod.CHAPTERS]
    if extra:
        chs += [dict(c) for c in extra.CHAPTERS]
    b["chapters"] = chs
    books.append(b)

data = {"appName": "Market Mastery Academy", "version": 1, "books": books}

# ---------- validation ----------
errors = []
seen_ch = set()
for b in books:
    for k in ("id", "short", "title", "author", "color", "tagline", "blurb"):
        if k not in b:
            errors.append(f"book missing {k}: {b.get('id')}")
    for i, c in enumerate(b["chapters"]):
        if c["id"] in seen_ch:
            errors.append(f"duplicate chapter id {c['id']}")
        seen_ch.add(c["id"])
        if c["num"] != i + 1:
            errors.append(f"{c['id']}: num {c['num']} != position {i+1}")
        for k in ("id", "num", "title", "blurb", "concepts", "quiz", "cards"):
            if k not in c:
                errors.append(f"{c['id']} missing {k}")
        if not (2 <= len(c["concepts"]) <= 8):
            errors.append(f"{c['id']}: {len(c['concepts'])} concepts")
        if not (2 <= len(c["quiz"]) <= 10):
            errors.append(f"{c['id']}: {len(c['quiz'])} quiz questions")
        for qi, q in enumerate(c["quiz"]):
            if len(q["o"]) != 4:
                errors.append(f"{c['id']} q{qi}: {len(q['o'])} options")
            if not (0 <= q["a"] < len(q["o"])):
                errors.append(f"{c['id']} q{qi}: answer index {q['a']} out of range")
            if q.get("type") == "chart" and "shape" not in q:
                errors.append(f"{c['id']} q{qi}: chart question missing shape")
            for k in ("q", "o", "a", "x"):
                if k not in q:
                    errors.append(f"{c['id']} q{qi} missing {k}")
        if not (1 <= len(c["cards"]) <= 8):
            errors.append(f"{c['id']}: {len(c['cards'])} cards")
        for cd in c["cards"]:
            if "term" not in cd or "def" not in cd:
                errors.append(f"{c['id']}: bad card {cd}")

if errors:
    print("VALIDATION ERRORS:")
    for e in errors:
        print(" -", e)
    sys.exit(1)

os.makedirs(os.path.join(ROOT, "data"), exist_ok=True)
os.makedirs(os.path.join(ROOT, "js"), exist_ok=True)

with open(os.path.join(ROOT, "data", "content.json"), "w") as f:
    json.dump(data, f, indent=1, ensure_ascii=False)

with open(os.path.join(ROOT, "js", "data.js"), "w") as f:
    f.write("/* generated by tools/build.py — do not edit by hand */\n")
    f.write("window.APP_DATA = ")
    json.dump(data, f, ensure_ascii=False, separators=(",", ":"))
    f.write(";\n")

n_ch = sum(len(b["chapters"]) for b in books)
n_q = sum(len(c["quiz"]) for b in books for c in b["chapters"])
n_cards = sum(len(c["cards"]) for b in books for c in b["chapters"])
n_concepts = sum(len(c["concepts"]) for b in books for c in b["chapters"])
print(f"OK: {len(books)} books, {n_ch} chapters, {n_concepts} concepts, {n_q} quiz questions, {n_cards} flashcards")
for b in books:
    print(f"  - {b['short']}: {b['title']} ({len(b['chapters'])} chapters)")
